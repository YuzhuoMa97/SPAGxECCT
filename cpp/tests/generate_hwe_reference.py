"""Regenerate or check the exact conditional-HWE fixtures (Python 3.8+).

Uses integer likelihood weights and exact tie comparisons; only the final
logarithm uses Decimal. No application code or external Python packages are
called. Run from any directory:

    python3 -B tests/generate_hwe_reference.py
    python3 -B tests/generate_hwe_reference.py --write
"""
from pathlib import Path
from decimal import Decimal, localcontext
import argparse
import math
import re


def references(panel):
    result = []
    for het, hom1, hom2 in panel:
        n = het + hom1 + hom2
        rare = het + 2 * min(hom1, hom2)
        observed = (1 << het) * math.comb(n, het) * math.comb(n - het, (rare - het) // 2)
        h = rare % 2
        weight = (1 << h) * math.comb(n, h) * math.comb(n - h, (rare - h) // 2)
        denominator = math.comb(2 * n, rare)
        total, tail = 0, 0
        while h <= rare:
            total += weight
            if weight <= observed:
                tail += weight
            homr = (rare - h) // 2
            homc = n - h - homr
            if h + 2 <= rare:
                weight, remainder = divmod(weight * 4 * homr * homc, (h + 2) * (h + 1))
                assert remainder == 0
            h += 2
        assert total == denominator
        values = []
        for precision in (80, 120):
            with localcontext() as context:
                context.prec = precision
                probability = Decimal(tail) / Decimal(denominator)
                values.append(-probability.log10() if probability != 1 else Decimal(0))
        with localcontext() as context:
            context.prec = 65
            assert +values[0] == +values[1]
        result.append((het, hom1, hom2, str(values[1])))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Write the checked fixture header.")
    args = parser.parse_args()
    here = Path(__file__).resolve().parent
    source = (here / "log10p_test.cpp").read_text(encoding="utf-8")
    section = source.split("inline std::vector<Counts> panel() {", 1)[1].split("};", 1)[0]
    panel = [tuple(map(int, values)) for values in re.findall(r"\{(\d+),\s*(\d+),\s*(\d+)\}", section)]
    assert len(panel) == 26
    rows = references(panel)
    lines = [
        "#pragma once", "", "namespace test_reference {",
        "// Generated by exact integer conditional-HWE enumeration, then Decimal log10.",
        "// Integer weights sum exactly to C(2N, rare); ties are compared exactly.",
        "// Decimal precision 80 and 120 agree after rounding to 65 significant digits.",
        "struct ExactHweReference { unsigned het, hom1, hom2; double negLog10P; };",
        "static const ExactHweReference exact_hwe_reference[] = {",
    ]
    for het, hom1, hom2, value in rows:
        lines.append("    {%d, %d, %d, %s}," % (het, hom1, hom2, value))
    lines.extend(["};", "} // namespace test_reference", ""])
    expected = "\n".join(lines)
    header = here / "exact_hwe_reference.hpp"
    if args.write:
        header.write_text(expected, encoding="utf-8")
    else:
        assert header.read_text(encoding="utf-8") == expected, "Fixture header differs; inspect before regenerating."
    print("26 exact conditional-HWE fixtures checked; integer masses normalize exactly; Decimal 80/120 digits agree.")


if __name__ == "__main__":
    main()
